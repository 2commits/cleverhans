#!/usr/bin/env node
// Generates the envelope types of @cleverhans/react from the JSON Schemas of
// the envelope, the way protoc generates code from a .proto file:
//
//   spec/schemas/client-event.json ─┐
//   spec/schemas/server-event.json ─┴─> cleverhans-react/src/generated/envelope.ts
//
//   node scripts/codegen-envelope.mjs          write the file
//   node scripts/codegen-envelope.mjs --check  exit 1 when the committed file is stale
//
// Run it through `pnpm codegen` / `pnpm codegen:check` from typescript/.
//
// The schemas are read as they are; the script never writes them. Before the
// generator sees a schema, three rewrites make json-schema-to-typescript emit
// the type the schema means. None changes what a schema accepts:
//
// 1. An object schema without declared properties (`params`, `slots`,
//    `extensions`) is a map. The generator's `additionalProperties: false`
//    default (set below, so messages get no index signature) would turn it into
//    `{}`; it gets an explicit `additionalProperties: true` and becomes
//    `{ [k: string]: unknown }`.
// 2. A `$ref` with sibling annotations (`{ "$ref": …, "description": … }`) is
//    rewritten to `{ "description": …, "allOf": [{ "$ref": … }] }`, which means
//    the same in draft 2020-12. Otherwise the generator merges the annotation
//    into a copy of the target and emits a duplicate type (`Context1`).
// 3. A schema with annotations only (`{ "description": … }`, any JSON value)
//    becomes `unknown`. The generator would emit an object type.
//
// A `$ref` with sibling keywords that are not annotations is refused, so a new
// construct is looked at before it is generated.

import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { compile } from "json-schema-to-typescript";

const WORKSPACE = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const REPO = path.resolve(WORKSPACE, "..");

/** Each schema file and the name of its root type. */
const SOURCES = [
  { file: "spec/schemas/client-event.json", root: "ClientEvent" },
  { file: "spec/schemas/server-event.json", root: "ServerEvent" },
];

const OUTPUT = "typescript/cleverhans-react/src/generated/envelope.ts";

/**
 * Schema names that would make a bad TypeScript export. `Error` would shadow
 * the global `Error` type wherever the declarations are read.
 */
const RENAMES = { Error: "ErrorMessage" };

const ANNOTATIONS = new Set([
  "title",
  "description",
  "$comment",
  "examples",
  "default",
  "deprecated",
  "readOnly",
  "writeOnly",
]);

const HEADER = `/**
 * GENERATED FILE, do not edit by hand.
 *
 * Generated by typescript/scripts/codegen-envelope.mjs (json-schema-to-typescript)
 * from spec/schemas/client-event.json and spec/schemas/server-event.json.
 * To change a type, change the schema (and its Rust type, see spec/schemas/README.md),
 * then regenerate from typescript/:
 *
 *   pnpm codegen         # rewrite this file
 *   pnpm codegen:check   # fail when this file is stale (CI runs it)
 */
`;

/** Subschema positions of draft 2020-12, by how they hold subschemas. */
const SINGLE = [
  "additionalProperties",
  "unevaluatedProperties",
  "items",
  "unevaluatedItems",
  "contains",
  "propertyNames",
  "not",
  "if",
  "then",
  "else",
];
const ARRAYS = ["allOf", "anyOf", "oneOf", "prefixItems"];
const MAPS = ["$defs", "definitions", "properties", "patternProperties", "dependentSchemas"];

function isObject(value) {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

/** Returns a rewritten copy of `schema` (see the rules at the top). */
function prepare(schema, where) {
  if (!isObject(schema)) {
    return schema;
  }
  let out = { ...schema };
  for (const key of SINGLE) {
    if (key in out) out[key] = prepare(out[key], `${where}/${key}`);
  }
  for (const key of ARRAYS) {
    if (Array.isArray(out[key])) out[key] = out[key].map((s, i) => prepare(s, `${where}/${key}/${i}`));
  }
  for (const key of MAPS) {
    if (isObject(out[key])) {
      out[key] = Object.fromEntries(
        Object.entries(out[key]).map(([k, s]) => [k, prepare(s, `${where}/${key}/${k}`)]),
      );
    }
  }

  const keys = Object.keys(out);
  // Rule 2: `$ref` with sibling annotations.
  if ("$ref" in out && keys.length > 1) {
    const siblings = keys.filter((k) => k !== "$ref");
    const other = siblings.filter((k) => !ANNOTATIONS.has(k));
    if (other.length > 0) {
      throw new Error(
        `${where}: $ref next to ${other.join(", ")} is not supported by codegen-envelope.mjs; ` +
          "extend the script before using it in a schema",
      );
    }
    const { $ref, ...annotations } = out;
    out = { ...annotations, allOf: [{ $ref }] };
  }
  // Rule 3: annotations only, i.e. any JSON value.
  if (keys.length > 0 && keys.every((k) => ANNOTATIONS.has(k))) {
    out = { ...out, tsType: "unknown" };
  }
  // Rule 1: an object without declared properties is a map.
  const hasShape = ["properties", "patternProperties", "additionalProperties", "unevaluatedProperties"]
    .concat(ARRAYS)
    .some((k) => k in out);
  if (out.type === "object" && !hasShape) {
    out = { ...out, additionalProperties: true };
  }
  return out;
}

async function generate() {
  const parts = [];
  for (const source of SOURCES) {
    const file = path.join(REPO, source.file);
    const schema = JSON.parse(await readFile(file, "utf8"));
    const ts = await compile(prepare(schema, source.file), source.root, {
      // Messages and shapes are open on the wire (receivers ignore unknown
      // fields) but must stay closed in TypeScript, or typos go unchecked.
      additionalProperties: false,
      bannerComment: "",
      cwd: path.dirname(file),
      customName: (s, key) => {
        if (s.$id === schema.$id) return source.root;
        return RENAMES[s.title ?? key];
      },
      // Only types the root reaches; every $defs entry is reachable today.
      unreachableDefinitions: false,
      // `unknown`, never `any`, for values the schema leaves open.
      unknownAny: true,
      // Index signatures (maps) read as `unknown`, already includes undefined.
      strictIndexSignatures: false,
      // The house style of the hand-written TypeScript in this workspace.
      style: {
        printWidth: 100,
        singleQuote: false,
        semi: true,
        trailingComma: "all",
        bracketSpacing: true,
        tabWidth: 2,
        useTabs: false,
        endOfLine: "lf",
      },
    });
    parts.push(ts.trim());
  }

  const names = new Map();
  for (const [i, part] of parts.entries()) {
    for (const match of part.matchAll(/^export (?:interface|type) (\w+)/gm)) {
      const name = match[1];
      if (names.has(name)) {
        throw new Error(
          `type ${name} is declared by both ${SOURCES[names.get(name)].file} and ${SOURCES[i].file}`,
        );
      }
      if (name in RENAMES) {
        throw new Error(`generated a type named ${name}; RENAMES did not apply`);
      }
      names.set(name, i);
    }
  }

  return `${HEADER}\n${parts.join("\n\n")}\n`;
}

async function main() {
  const check = process.argv.includes("--check");
  const target = path.join(REPO, OUTPUT);
  const generated = await generate();

  if (check) {
    let current = null;
    try {
      current = await readFile(target, "utf8");
    } catch {
      // Missing counts as stale.
    }
    if (current !== generated) {
      console.error(
        `${OUTPUT} is stale: it differs from what spec/schemas/{client,server}-event.json produce.\n` +
          "Run `pnpm codegen` in typescript/ and commit the result.",
      );
      process.exit(1);
    }
    console.log(`${OUTPUT} is up to date.`);
    return;
  }

  await mkdir(path.dirname(target), { recursive: true });
  await writeFile(target, generated);
  console.log(`wrote ${OUTPUT}`);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
